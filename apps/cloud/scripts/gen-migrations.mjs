// Embed src/db/migrations/*.sql into src/db/migrations.generated.ts so bundled
// deployments (Vercel functions) carry the schema without reading the filesystem.
//   node apps/cloud/scripts/gen-migrations.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/db');
const files = fs.readdirSync(path.join(dir, 'migrations')).filter((f) => f.endsWith('.sql')).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(fs.readFileSync(path.join(dir, 'migrations', f), 'utf8'))} },`).join('\n');
const out = `// Generated by scripts/gen-migrations.mjs from src/db/migrations/*.sql. Do not edit.\nexport const MIGRATIONS: ReadonlyArray<{ name: string; sql: string }> = [\n${body}\n];\n`;
const target = path.join(dir, 'migrations.generated.ts');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== out) {
    console.error('src/db/migrations.generated.ts is stale; run: node apps/cloud/scripts/gen-migrations.mjs');
    process.exit(1);
  }
  console.log(`migrations up to date (${files.length})`);
} else {
  fs.writeFileSync(target, out);
  console.log(`wrote ${files.length} migration(s)`);
}
